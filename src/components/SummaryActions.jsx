// src/components/SummaryActions.jsx
import React, { useState } from 'react'
import { Copy, Check, Printer } from 'lucide-react'

const PRINT_STYLES = {
  citizen: `
    body { font-family: Arial, sans-serif; line-height: 1.6; color: #000; margin: 20px; max-width: 800px; }
    .header { text-align: center; margin-bottom: 20px; border-bottom: 2px solid #000; padding-bottom: 10px; }
    .footer { margin-top: 30px; text-align: center; font-size: 10pt; color: #666; }
    @media print { body { margin: 0; } .header { margin-top: 0; } }`,
  professional: `
    body { font-family: 'Times New Roman', serif; line-height: 1.6; color: #000; margin: 25px; max-width: 700px; }
    .summary-content { text-align: justify; }
    .header { text-align: center; margin-bottom: 30px; border-bottom: 3px double #000; padding-bottom: 15px; }
    .footer { margin-top: 40px; text-align: center; font-size: 10pt; color: #666; border-top: 1px solid #000; padding-top: 10px; }
    @media print { body { margin: 15mm; } .header { margin-top: 0; } }`,
}

const PRINT_CHROME = {
  citizen: {
    title: 'Legal Document Summary',
    header: '<h1>Legal Document Summary</h1><p>Generated on {date}</p>',
    footer: '<p>Generated by Legal Document Summarizer</p>',
  },
  professional: {
    title: 'Legal Analysis Report',
    header: '<h1>LEGAL ANALYSIS REPORT</h1><p>Professional Document Analysis</p><p>Generated on {date}</p>',
    footer: '<p><strong>CONFIDENTIAL - ATTORNEY WORK PRODUCT</strong></p><p>Generated by Legal Professional Document Analyzer</p>',
  },
}

// contentRef must point at React-rendered output (react-markdown never emits raw HTML),
// so the model's text is escaped before it reaches the print window.
const SummaryActions = ({ text, contentRef, variant = 'citizen', printLabel, copyLabel }) => {
  const [copied, setCopied] = useState(false)

  const copyToClipboard = async () => {
    try {
      await navigator.clipboard.writeText(text)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch (err) {
      console.error('Failed to copy text: ', err)
    }
  }

  const handlePrint = () => {
    const chrome = PRINT_CHROME[variant]
    const date = new Date().toLocaleString()
    const printWindow = window.open('', '_blank')
    printWindow.document.write(`<!DOCTYPE html><html><head><title>${chrome.title}</title>
      <style>${PRINT_STYLES[variant]}</style></head><body>
      <div class="header">${chrome.header.replace('{date}', date)}</div>
      <div class="summary-content">${contentRef.current?.innerHTML ?? ''}</div>
      <div class="footer">${chrome.footer}</div></body></html>`)
    printWindow.document.close()
    printWindow.focus()
    printWindow.print()
    printWindow.close()
  }

  return (
    <div className="summary-actions no-print">
      <button onClick={handlePrint} className="print-btn">
        <Printer size={16} />
        {printLabel}
      </button>
      <button onClick={copyToClipboard} className="action-btn primary">
        {copied ? <Check size={16} /> : <Copy size={16} />}
        {copied ? 'Copied!' : copyLabel}
      </button>
    </div>
  )
}

export default SummaryActions
