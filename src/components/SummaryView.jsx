import React, { useState } from 'react'
import { FileText, Clock, BarChart3, Copy, Check, Printer } from 'lucide-react'
import SocialShare from './SocialShare'
import SimpleAudioPlayer from './SimpleAudioPlayer'

const SummaryView = ({ originalText, summary }) => {
  const [activeTab, setActiveTab] = useState('summary')
  const [copied, setCopied] = useState(false)

  const copyToClipboard = async () => {
    try {
      await navigator.clipboard.writeText(summary)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch (err) {
      console.error('Failed to copy text: ', err)
    }
  }

  const handlePrint = () => {
    // Create a print-friendly version
    const printWindow = window.open('', '_blank')
    printWindow.document.write(`
      <!DOCTYPE html>
      <html>
        <head>
          <title>Legal Document Summary</title>
          <style>
            body {
              font-family: Arial, sans-serif;
              line-height: 1.6;
              color: #000;
              margin: 20px;
              max-width: 800px;
            }
            .summary-content {
              white-space: pre-line;
              font-size: 12pt;
            }
            .header {
              text-align: center;
              margin-bottom: 20px;
              border-bottom: 2px solid #000;
              padding-bottom: 10px;
            }
            .footer {
              margin-top: 30px;
              text-align: center;
              font-size: 10pt;
              color: #666;
            }
            @media print {
              body { margin: 0; }
              .header { margin-top: 0; }
            }
          </style>
        </head>
        <body>
          <div class="header">
            <h1>Legal Document Summary</h1>
            <p>Generated on ${new Date().toLocaleDateString()}</p>
          </div>
          <div class="summary-content">${summary}</div>
          <div class="footer">
            <p>Generated by Legal Document Summarizer</p>
          </div>
        </body>
      </html>
    `)
    printWindow.document.close()
    printWindow.focus()
    printWindow.print()
    printWindow.close()
  }

  const calculateReduction = () => {
    const originalWords = originalText.split(/\s+/).length
    const summaryWords = summary.split(/\s+/).length
    const reduction = ((originalWords - summaryWords) / originalWords) * 100
    return Math.round(reduction)
  }

  const calculateReadingTime = (text) => {
    const words = text.split(/\s+/).length
    const readingSpeed = 200
    return Math.ceil(words / readingSpeed)
  }

  const calculateTimeSaved = () => {
    const originalTime = calculateReadingTime(originalText)
    const summaryTime = calculateReadingTime(summary)
    const timeSaved = ((originalTime - summaryTime) / originalTime) * 100
    return Math.round(timeSaved)
  }

  return (
    <div className="component-card">
      {/* Header with Actions */}
      <div className="summary-header">
        <h2 className="summary-title">Document Summary</h2>
        <div className="summary-actions no-print">
          <button
            onClick={handlePrint}
            className="print-btn"
          >
            <Printer size={16} />
            Print Summary
          </button>
          <button
            onClick={copyToClipboard}
            className="action-btn primary"
          >
            {copied ? <Check size={16} /> : <Copy size={16} />}
            {copied ? 'Copied!' : 'Copy'}
          </button>
        </div>
      </div>

      {/* Tabs */}
      <div className="tabs no-print">
        <button
          onClick={() => setActiveTab('summary')}
          className={`tab ${activeTab === 'summary' ? 'active' : ''}`}
        >
          <FileText className="w-4 h-4 inline mr-2" />
          Summary
        </button>
        <button
          onClick={() => setActiveTab('metrics')}
          className={`tab ${activeTab === 'metrics' ? 'active' : ''}`}
        >
          <BarChart3 className="w-4 h-4 inline mr-2" />
          Metrics
        </button>
      </div>

      {/* Content */}
      <div>
        {activeTab === 'summary' && (
          <div>
            <div className="prose">
              <p className="text-gray-700 dark:text-gray-300 leading-relaxed whitespace-pre-line">
                {summary}
              </p>
            </div>
            <div className="no-print">
              <SocialShare summary={summary} />
            </div>
          </div>
        )}

        {activeTab === 'metrics' && (
          <div className="space-y-6 no-print">
            <h3 className="text-lg font-semibold text-gray-900 dark:text-white">
              Reading Efficiency Metrics
            </h3>

            <div className="metrics-grid">
              <div className="metric-card">
                <BarChart3 className="h-8 w-8 text-blue-600 dark:text-blue-400 mx-auto mb-2" />
                <p className="metric-value">{calculateReduction()}%</p>
                <p className="metric-label">Content Reduction</p>
              </div>

              <div className="metric-card">
                <Clock className="h-8 w-8 text-green-600 dark:text-green-400 mx-auto mb-2" />
                <p className="metric-value">{calculateTimeSaved()}%</p>
                <p className="metric-label">Time Saved</p>
              </div>
            </div>

            <div className="stats-grid">
              <div className="stat-item">
                <span className="stat-label">Original words:</span>
                <span className="stat-value">{originalText.split(/\s+/).length.toLocaleString()}</span>
              </div>
              <div className="stat-item">
                <span className="stat-label">Summary words:</span>
                <span className="stat-value">{summary.split(/\s+/).length.toLocaleString()}</span>
              </div>
              <div className="stat-item">
                <span className="stat-label">Words removed:</span>
                <span className="stat-value">
                  {(originalText.split(/\s+/).length - summary.split(/\s+/).length).toLocaleString()}
                </span>
              </div>
              <div className="stat-item">
                <span className="stat-label">Reading time:</span>
                <span className="stat-value">
                  {calculateReadingTime(originalText)}min → {calculateReadingTime(summary)}min
                </span>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  )
}

export default SummaryView