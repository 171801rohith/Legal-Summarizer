import React, { useState } from 'react'
import { FileText, Clock, BarChart3, Copy, Check, Printer, Scale, BookOpen, Users, Calendar } from 'lucide-react'
import SocialShare from '../SocialShare'
import SimpleAudioPlayer from '../SimpleAudioPlayer'

const LawyerSummaryView = ({ originalText, summary, keySections }) => {
  const [activeTab, setActiveTab] = useState('analysis')
  const [copied, setCopied] = useState(false)

  const copyToClipboard = async () => {
    try {
      await navigator.clipboard.writeText(summary)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch (err) {
      console.error('Failed to copy text: ', err)
    }
  }

  const handlePrint = () => {
    // Create a professional print-friendly version for lawyers
    const printWindow = window.open('', '_blank')
    printWindow.document.write(`
      <!DOCTYPE html>
      <html>
        <head>
          <title>Legal Analysis Report</title>
          <style>
            body {
              font-family: 'Times New Roman', serif;
              line-height: 1.6;
              color: #000;
              margin: 25px;
              max-width: 700px;
            }
            .summary-content {
              white-space: pre-line;
              font-size: 12pt;
              text-align: justify;
            }
            .header {
              text-align: center;
              margin-bottom: 30px;
              border-bottom: 3px double #000;
              padding-bottom: 15px;
            }
            .footer {
              margin-top: 40px;
              text-align: center;
              font-size: 10pt;
              color: #666;
              border-top: 1px solid #000;
              padding-top: 10px;
            }
            .legal-header {
              font-size: 16pt;
              font-weight: bold;
              margin-bottom: 5px;
            }
            .sub-header {
              font-size: 12pt;
              color: #444;
              margin-bottom: 15px;
            }
            @media print {
              body { margin: 15mm; }
              .header { margin-top: 0; }
            }
          </style>
        </head>
        <body>
          <div class="header">
            <div class="legal-header">LEGAL ANALYSIS REPORT</div>
            <div class="sub-header">Professional Document Analysis</div>
            <p>Generated on ${new Date().toLocaleDateString()} at ${new Date().toLocaleTimeString()}</p>
          </div>
          <div class="summary-content">${summary}</div>
          <div class="footer">
            <p><strong>CONFIDENTIAL - ATTORNEY WORK PRODUCT</strong></p>
            <p>Generated by Legal Professional Document Analyzer</p>
          </div>
        </body>
      </html>
    `)
    printWindow.document.close()
    printWindow.focus()
    printWindow.print()
    printWindow.close()
  }

  const calculateMetrics = () => {
    const originalWords = originalText.split(/\s+/).length
    const summaryWords = summary.split(/\s+/).length
    const reduction = Math.round(((originalWords - summaryWords) / originalWords) * 100)
    const readingTime = (text) => Math.ceil(text.split(/\s+/).length / 300) // Lawyers read faster
    const timeSaved = Math.round(((readingTime(originalText) - readingTime(summary)) / readingTime(originalText)) * 100)
    
    return { reduction, timeSaved, originalWords, summaryWords, readingTime }
  }

  const { reduction, timeSaved, originalWords, summaryWords, readingTime } = calculateMetrics()

  const getLegalComplexity = () => {
    const legalTerms = ['section', 'article', 'act', 'rule', 'regulation', 'statute', 'precedent', 'jurisdiction']
    const termCount = legalTerms.filter(term => 
      originalText.toLowerCase().includes(term)
    ).length
    return termCount > 10 ? 'High' : termCount > 5 ? 'Medium' : 'Low'
  }

  return (
    <div className="component-card professional-summary">
      {/* Header with Actions */}
      <div className="summary-header">
        <div className="flex items-center gap-3">
          <Scale className="professional-summary-icon" />
          <div>
            <h2 className="summary-title">Legal Analysis Report</h2>
            <p className="professional-subtitle">Comprehensive document analysis for legal professionals</p>
          </div>
        </div>
        <div className="summary-actions no-print">
          <SimpleAudioPlayer size="small" />
          <button
            onClick={handlePrint}
            className="print-btn"
          >
            <Printer size={16} />
            Print Report
          </button>
          <button
            onClick={copyToClipboard}
            className="action-btn primary"
          >
            {copied ? <Check size={16} /> : <Copy size={16} />}
            {copied ? 'Copied!' : 'Copy Analysis'}
          </button>
        </div>
      </div>

      {/* Tabs */}
      <div className="tabs no-print">
        <button
          onClick={() => setActiveTab('analysis')}
          className={`tab ${activeTab === 'analysis' ? 'active' : ''}`}
        >
          <Scale className="w-4 h-4 inline mr-2" />
          Legal Analysis
        </button>
        <button
          onClick={() => setActiveTab('metrics')}
          className={`tab ${activeTab === 'metrics' ? 'active' : ''}`}
        >
          <BarChart3 className="w-4 h-4 inline mr-2" />
          Professional Metrics
        </button>
        <button
          onClick={() => setActiveTab('sections')}
          className={`tab ${activeTab === 'sections' ? 'active' : ''}`}
        >
          <BookOpen className="w-4 h-4 inline mr-2" />
          Key Legal Elements
        </button>
      </div>

      {/* Content */}
      <div>
        {activeTab === 'analysis' && (
          <div>
            <div className="professional-analysis-content">
              <div className="analysis-header">
                <h3 className="analysis-title">Legal Document Analysis</h3>
                <div className="complexity-badge">
                  Complexity: {getLegalComplexity()}
                </div>
              </div>
              <div className="prose">
                <p className="text-gray-700 dark:text-gray-300 leading-relaxed whitespace-pre-line">
                  {summary}
                </p>
              </div>
            </div>
            <div className="no-print">
              <SocialShare summary={summary} title="Legal Analysis Report" />
            </div>
          </div>
        )}

        {activeTab === 'metrics' && (
          <div className="space-y-6 no-print">
            <h3 className="text-lg font-semibold text-gray-900 dark:text-white">
              Professional Metrics
            </h3>

            <div className="metrics-grid">
              <div className="metric-card">
                <BarChart3 className="h-8 w-8 text-blue-600 dark:text-blue-400 mx-auto mb-2" />
                <p className="metric-value">{reduction}%</p>
                <p className="metric-label">Content Reduction</p>
              </div>

              <div className="metric-card">
                <Clock className="h-8 w-8 text-green-600 dark:text-green-400 mx-auto mb-2" />
                <p className="metric-value">{timeSaved}%</p>
                <p className="metric-label">Time Saved</p>
              </div>

              <div className="metric-card">
                <FileText className="h-8 w-8 text-purple-600 dark:text-purple-400 mx-auto mb-2" />
                <p className="metric-value">{readingTime(originalText)}→{readingTime(summary)}min</p>
                <p className="metric-label">Reading Time</p>
              </div>

              <div className="metric-card">
                <Scale className="h-8 w-8 text-orange-600 dark:text-orange-400 mx-auto mb-2" />
                <p className="metric-value">{getLegalComplexity()}</p>
                <p className="metric-label">Legal Complexity</p>
              </div>
            </div>

            <div className="stats-grid">
              <div className="stat-item">
                <span className="stat-label">Original Document:</span>
                <span className="stat-value">{originalWords.toLocaleString()} words</span>
              </div>
              <div className="stat-item">
                <span className="stat-label">Analysis:</span>
                <span className="stat-value">{summaryWords.toLocaleString()} words</span>
              </div>
              <div className="stat-item">
                <span className="stat-label">Words Removed:</span>
                <span className="stat-value">{(originalWords - summaryWords).toLocaleString()}</span>
              </div>
              <div className="stat-item">
                <span className="stat-label">Retention Rate:</span>
                <span className="stat-value">{Math.round((summaryWords / originalWords) * 100)}%</span>
              </div>
            </div>
          </div>
        )}

        {activeTab === 'sections' && (
          <div className="space-y-4 no-print">
            <h3 className="text-lg font-semibold text-gray-900 dark:text-white">
              Key Legal Elements
            </h3>
            <div className="legal-elements-grid">
              {keySections.map((section, index) => (
                <div key={index} className="legal-element-card">
                  <div className="legal-element-icon">
                    {section.type === 'verdict' && <Scale size={20} />}
                    {section.type === 'parties' && <Users size={20} />}
                    {section.type === 'legal_sections' && <BookOpen size={20} />}
                    {section.type === 'dates' && <Calendar size={20} />}
                  </div>
                  <div className="legal-element-content">
                    <span className="legal-element-type">{section.type.replace('_', ' ').toUpperCase()}</span>
                    <p className="legal-element-text">{section.content}</p>
                    {section.relevance && (
                      <span className="legal-element-relevance">Relevance: {section.relevance}</span>
                    )}
                  </div>
                </div>
              ))}
            </div>
          </div>
        )}
      </div>
    </div>
  )
}

export default LawyerSummaryView